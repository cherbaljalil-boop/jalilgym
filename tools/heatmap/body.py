def mirror(d: str) -> str:
    def flip(m):
        x, y = float(m.group(1)), float(m.group(2))
        return f"{100 - x:g},{y:g}"
    return re.sub(r"(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)", flip, d)

def full(paths):
    return [p for d in paths for p in (d, mirror(d))]
